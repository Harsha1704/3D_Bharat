from abc import ABC, abstractmethod
import logging
from typing import Any, Dict, List, Optional
import httpx

from app.core.config import settings

logger = logging.getLogger("3d_bharat.ai_provider")


class BaseAIProvider(ABC):
    """
    Abstract adapter for LLM providers.
    Allows swapping between OpenAI, Gemini, Ollama, or Offline Fallback without altering RAG logic.
    """

    @abstractmethod
    def generate_answer(
        self,
        prompt: str,
        system_prompt: str,
        max_tokens: int = 1000,
    ) -> str:
        pass

    @abstractmethod
    def get_provider_info(self) -> Dict[str, Any]:
        pass


class OpenAICompatibleProvider(BaseAIProvider):
    """
    Adapter for OpenAI or any OpenAI-compatible API (DeepSeek, Groq, vLLM, etc.)
    """

    def __init__(
        self,
        api_key: str,
        model: str = "gpt-4o-mini",
        base_url: Optional[str] = None,
        timeout: int = 30,
        max_retries: int = 2,
    ):
        self.api_key = api_key
        self.model = model
        self.base_url = (base_url or "https://api.openai.com/v1").rstrip("/")
        self.timeout = timeout
        self.max_retries = max_retries

    def generate_answer(
        self,
        prompt: str,
        system_prompt: str,
        max_tokens: int = 1000,
    ) -> str:
        headers = {
            "Authorization": f"Bearer {self.api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": prompt},
            ],
            "max_tokens": max_tokens,
            "temperature": 0.1,  # Strict factual determinism
        }

        endpoint = f"{self.base_url}/chat/completions"

        for attempt in range(self.max_retries + 1):
            try:
                with httpx.Client(timeout=self.timeout) as client:
                    response = client.post(endpoint, headers=headers, json=payload)
                    response.raise_for_status()
                    data = response.json()
                    choices = data.get("choices", [])
                    if choices and "message" in choices[0]:
                        return choices[0]["message"].get("content", "").strip()
                    return "No response generated by model."
            except httpx.HTTPStatusError as exc:
                logger.error("OpenAI-compatible HTTP error (%s): %s", exc.response.status_code, exc.response.text)
                if attempt == self.max_retries:
                    raise RuntimeError(f"AI Provider error: HTTP {exc.response.status_code}")
            except Exception as exc:
                logger.error("OpenAI-compatible connection failure: %s", exc)
                if attempt == self.max_retries:
                    raise RuntimeError("AI Provider connection timed out or unreachable.")

        return "No answer received from AI provider."

    def get_provider_info(self) -> Dict[str, Any]:
        return {
            "provider": "openai_compatible",
            "model": self.model,
            "configured": True,
            "base_url": self.base_url,
        }


class GeminiProvider(BaseAIProvider):
    """
    Adapter for Google Gemini API
    """

    def __init__(
        self,
        api_key: str,
        model: str = "gemini-1.5-flash",
        timeout: int = 30,
        max_retries: int = 2,
    ):
        self.api_key = api_key
        self.model = model
        self.timeout = timeout
        self.max_retries = max_retries

    def generate_answer(
        self,
        prompt: str,
        system_prompt: str,
        max_tokens: int = 1000,
    ) -> str:
        endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"
        payload = {
            "system_instruction": {"parts": [{"text": system_prompt}]},
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {
                "maxOutputTokens": max_tokens,
                "temperature": 0.1,
            },
        }

        for attempt in range(self.max_retries + 1):
            try:
                with httpx.Client(timeout=self.timeout) as client:
                    res = client.post(endpoint, json=payload)
                    res.raise_for_status()
                    data = res.json()
                    candidates = data.get("candidates", [])
                    if candidates:
                        parts = candidates[0].get("content", {}).get("parts", [])
                        if parts:
                            return parts[0].get("text", "").strip()
                    return "No response generated by Gemini model."
            except Exception as exc:
                logger.error("Gemini provider error: %s", exc)
                if attempt == self.max_retries:
                    raise RuntimeError("Gemini API request failed.")

        return "No answer received from Gemini provider."

    def get_provider_info(self) -> Dict[str, Any]:
        return {
            "provider": "gemini",
            "model": self.model,
            "configured": True,
        }


class OllamaProvider(BaseAIProvider):
    """
    Adapter for local Ollama service
    """

    def __init__(
        self,
        model: str = "llama3.2",
        base_url: str = "http://localhost:11434",
        timeout: int = 60,
    ):
        self.model = model
        self.base_url = base_url.rstrip("/")
        self.timeout = timeout

    def generate_answer(
        self,
        prompt: str,
        system_prompt: str,
        max_tokens: int = 1000,
    ) -> str:
        endpoint = f"{self.base_url}/api/generate"
        payload = {
            "model": self.model,
            "system": system_prompt,
            "prompt": prompt,
            "stream": False,
            "options": {"num_predict": max_tokens, "temperature": 0.1},
        }
        try:
            with httpx.Client(timeout=self.timeout) as client:
                res = client.post(endpoint, json=payload)
                res.raise_for_status()
                return res.json().get("response", "").strip()
        except Exception as exc:
            logger.error("Ollama connection error: %s", exc)
            raise RuntimeError("Ollama local service unreachable.")

    def get_provider_info(self) -> Dict[str, Any]:
        return {
            "provider": "ollama",
            "model": self.model,
            "configured": True,
            "base_url": self.base_url,
        }


class OfflineFallbackProvider(BaseAIProvider):
    """
    Deterministic factual fallback when external LLM credentials are not configured or unreachable.
    Synthesizes an honest, evidence-grounded summary directly from the supplied evidence blocks
    without hallucinating facts, citations, or URLs.
    """

    def generate_answer(
        self,
        prompt: str,
        system_prompt: str,
        max_tokens: int = 1000,
    ) -> str:
        # Check if prompt contains evidence citations
        if "[CITATION_" not in prompt or "No relevant evidence" in prompt:
            return (
                "The 3D BHARAT national heritage database does not contain sufficient documented or verified evidence "
                "to answer this specific inquiry. No corresponding ASI or UNESCO records were matched for this topic."
            )

        # Extract citation snippets from the prompt to build a grounded factual summary
        lines = prompt.splitlines()
        evidence_lines = []
        for line in lines:
            line_str = line.strip()
            if line_str.startswith("[CITATION_"):
                evidence_lines.append(line_str)

        if not evidence_lines:
            return (
                "Insufficient documented evidence found in the verified database. "
                "No historical claims can be established without primary source records."
            )

        summary_parts = [
            "Based directly on documented records in the 3D BHARAT heritage repository:"
        ]
        for idx, ev in enumerate(evidence_lines[:5], start=1):
            tag = f"[CITATION_{idx}]"
            content = ev.replace(tag, "").strip(" :-\t")
            summary_parts.append(f"• {content} {tag}")

        return "\n".join(summary_parts)

    def get_provider_info(self) -> Dict[str, Any]:
        return {
            "provider": "offline_fallback",
            "model": "grounded_rule_synthesizer",
            "configured": False,
            "status": "External LLM provider not configured. Operating in strict factual evidence mode.",
        }


def get_ai_provider() -> BaseAIProvider:
    """
    Factory function to instantiate the configured AI provider.
    Falls back safely to OfflineFallbackProvider if credentials are missing.
    """
    provider_name = (settings.AI_PROVIDER or "").strip().lower()

    if provider_name in ["openai", "openai_compatible"] and settings.AI_API_KEY:
        return OpenAICompatibleProvider(
            api_key=settings.AI_API_KEY,
            model=settings.AI_MODEL,
            base_url=settings.AI_API_BASE_URL,
            timeout=settings.AI_REQUEST_TIMEOUT_SECONDS,
            max_retries=settings.AI_MAX_RETRIES,
        )

    if provider_name in ["gemini", "google"] and settings.AI_API_KEY:
        return GeminiProvider(
            api_key=settings.AI_API_KEY,
            model=settings.AI_MODEL,
            timeout=settings.AI_REQUEST_TIMEOUT_SECONDS,
            max_retries=settings.AI_MAX_RETRIES,
        )

    if provider_name == "ollama":
        return OllamaProvider(
            model=settings.AI_MODEL,
            base_url=settings.AI_API_BASE_URL or "http://localhost:11434",
            timeout=settings.AI_REQUEST_TIMEOUT_SECONDS,
        )

    return OfflineFallbackProvider()
