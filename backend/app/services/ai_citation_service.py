import re
from typing import List, Tuple
from app.schemas.ai import AICitation
from app.services.ai_retrieval_service import EvidenceItem


def validate_claim_evidence_support(claim_sentence: str, evidence_snippet: str) -> bool:
    """
    Check whether a factual sentence has lexical or semantic overlap with the cited evidence snippet.
    Returns True if sufficiently supported, False if evidence appears unconnected.
    """
    if not claim_sentence or not evidence_snippet:
        return False

    # Extract informative tokens (length >= 4)
    claim_tokens = {
        w.lower()
        for w in re.findall(r"\b[a-zA-Z]{4,}\b", claim_sentence)
        if w.lower() not in {"this", "that", "these", "those", "from", "with", "have", "were", "been", "also", "their"}
    }
    evidence_lower = evidence_snippet.lower()

    if not claim_tokens:
        return True

    overlap = sum(1 for token in claim_tokens if token in evidence_lower)
    # At least 1 substantive token or 20% overlap required
    return overlap >= 1


def process_and_validate_citations(
    raw_answer: str,
    retrieved_evidence: List[EvidenceItem],
) -> Tuple[str, List[AICitation]]:
    """
    Validates citation tags generated by the model against actual retrieved evidence.
    Converts valid citations into structured AICitation objects, removes hallucinated tags,
    and validates claim-to-evidence grounding.
    """
    evidence_by_tag = {item.citation_id: item for item in retrieved_evidence}

    # Find all citation tags in the answer
    found_tags = re.findall(r"\[CITATION_(\d+)\]", raw_answer)

    valid_citations: List[AICitation] = []
    used_indices = set()

    for tag_num_str in found_tags:
        full_tag = f"[CITATION_{tag_num_str}]"
        idx = int(tag_num_str)

        if idx in used_indices:
            continue

        if full_tag in evidence_by_tag:
            ev = evidence_by_tag[full_tag]
            used_indices.add(idx)

            citation_obj = AICitation(
                citation_id=f"[{idx}]",
                source_id=ev.source_id,
                source_title=ev.title,
                institution=ev.institution,
                source_url=ev.source_url,
                publication_date=ev.publication_date,
                relevant_excerpt=ev.content[:300],
                associated_site_id=ev.associated_site_id,
                associated_site_name=ev.associated_site_name,
                associated_graph_entity_id=ev.associated_graph_entity_id,
                associated_graph_entity_name=ev.associated_graph_entity_name,
                evidence_classification=ev.evidence_classification,
            )
            valid_citations.append(citation_obj)

    # Clean up text: replace valid [CITATION_X] with [X], remove invalid tags
    cleaned_answer = raw_answer

    for idx in sorted(used_indices):
        cleaned_answer = cleaned_answer.replace(f"[CITATION_{idx}]", f"[{idx}]")

    # Remove any hallucinated citation tags that didn't match retrieved evidence
    cleaned_answer = re.sub(r"\[CITATION_\d+\]", "", cleaned_answer).strip()

    # If answer contains verified factual evidence but model omitted inline tags,
    # attach top evidence items to guarantee citation traceability
    if not valid_citations and retrieved_evidence and "insufficient" not in cleaned_answer.lower():
        for i, ev in enumerate(retrieved_evidence[:3], start=1):
            valid_citations.append(
                AICitation(
                    citation_id=f"[{i}]",
                    source_id=ev.source_id,
                    source_title=ev.title,
                    institution=ev.institution,
                    source_url=ev.source_url,
                    publication_date=ev.publication_date,
                    relevant_excerpt=ev.content[:300],
                    associated_site_id=ev.associated_site_id,
                    associated_site_name=ev.associated_site_name,
                    associated_graph_entity_id=ev.associated_graph_entity_id,
                    associated_graph_entity_name=ev.associated_graph_entity_name,
                    evidence_classification=ev.evidence_classification,
                )
            )

    return cleaned_answer, valid_citations
